import React, { useState } from 'react';
import { 
  Palette, 
  Save, 
  X, 
  RotateCcw,
  Check
} from 'lucide-react';
import { WhiteLabelConfig } from '../types';
import { Language, translations } from '../i18n/translations';

interface WhiteLabelSettingsModalProps {
  isOpen: boolean;
  onClose: () => void;
  config: WhiteLabelConfig;
  onSave: (updated: WhiteLabelConfig) => void;
  lang: Language;
}

export const WhiteLabelSettingsModal: React.FC<WhiteLabelSettingsModalProps> = ({
  isOpen,
  onClose,
  config,
  onSave,
  lang,
}) => {
  const t = translations[lang];
  const [formData, setFormData] = useState<WhiteLabelConfig>({ ...config });
  const [savedSuccess, setSavedSuccess] = useState(false);

  if (!isOpen) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    onSave(formData);
    setSavedSuccess(true);
    setTimeout(() => {
      setSavedSuccess(false);
      onClose();
    }, 1200);
  };

  const handleReset = () => {
    setFormData({
      agencyName: 'PublisherRocket Pro',
      agencyLogoUrl: '',
      tagline: 'Amazon KDP Market Intelligence & Keyword Suite',
      accentColor: '#4f46e5',
      contactEmail: 'contact@publisherintelligence.com',
      websiteUrl: 'https://publisherintelligence.com',
      reportFooterNote: 'Generated by Publisher Intelligence Suite - 100% Confidential Client Report.',
      clientName: 'Private Author / Publisher',
      isPresentationMode: false,
      watermarkEnabled: false,
    });
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md">
      <div className="glass-panel w-full max-w-2xl rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl overflow-hidden flex flex-col max-h-[90vh]">
        
        {/* Modal Header */}
        <div className="flex items-center justify-between p-5 border-b border-slate-800">
          <div className="flex items-center space-x-2.5 rtl:space-x-reverse">
            <div className="w-8 h-8 rounded-lg bg-indigo-600/20 text-indigo-400 flex items-center justify-center">
              <Palette className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">{t.whiteLabelTitle}</h3>
              <p className="text-xs text-slate-400">{t.whiteLabelSubtitle}</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Form */}
        <form onSubmit={handleSubmit} className="p-6 space-y-4 overflow-y-auto flex-1">
          
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelAgencyName}</label>
              <input
                type="text"
                value={formData.agencyName}
                onChange={(e) => setFormData({ ...formData, agencyName: e.target.value })}
                placeholder="e.g. Apex Publishing Lab"
                className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
              />
            </div>

            <div>
              <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelClientName}</label>
              <input
                type="text"
                value={formData.clientName}
                onChange={(e) => setFormData({ ...formData, clientName: e.target.value })}
                placeholder="e.g. John Doe / Stellar Media"
                className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
              />
            </div>
          </div>

          <div>
            <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelLogoUrl}</label>
            <input
              type="text"
              value={formData.agencyLogoUrl}
              onChange={(e) => setFormData({ ...formData, agencyLogoUrl: e.target.value })}
              placeholder="https://yourwebsite.com/logo.png"
              className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs font-mono focus:outline-none focus:border-indigo-500"
            />
          </div>

          <div>
            <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelTagline}</label>
            <input
              type="text"
              value={formData.tagline}
              onChange={(e) => setFormData({ ...formData, tagline: e.target.value })}
              placeholder="e.g. Amazon KDP Market Intelligence & Category Blueprint"
              className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
            />
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelEmail}</label>
              <input
                type="email"
                value={formData.contactEmail}
                onChange={(e) => setFormData({ ...formData, contactEmail: e.target.value })}
                placeholder="contact@youragency.com"
                className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
              />
            </div>

            <div>
              <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelWebsite}</label>
              <input
                type="text"
                value={formData.websiteUrl}
                onChange={(e) => setFormData({ ...formData, websiteUrl: e.target.value })}
                placeholder="https://youragency.com"
                className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
              />
            </div>
          </div>

          <div>
            <label className="text-xs font-bold text-slate-300 block mb-1">{t.labelFooterNote}</label>
            <textarea
              rows={2}
              value={formData.reportFooterNote}
              onChange={(e) => setFormData({ ...formData, reportFooterNote: e.target.value })}
              placeholder="Confidential book market dossier prepared exclusively for..."
              className="w-full px-3 py-2 rounded-xl bg-slate-950 border border-slate-700 text-white text-xs focus:outline-none focus:border-indigo-500"
            />
          </div>

          {/* Live Report Header Preview */}
          <div className="pt-2">
            <span className="text-xs font-bold text-slate-400 block mb-2">{t.liveHeaderPreview}</span>
            <div className="rounded-xl border border-slate-800 bg-slate-950 p-4 space-y-1">
              <div className="flex items-center justify-between">
                <span className="text-sm font-extrabold text-white">{formData.agencyName || 'Your Agency'}</span>
                <span className="text-[10px] text-indigo-400 font-semibold font-mono">CONFIDENTIAL REPORT</span>
              </div>
              <p className="text-[11px] text-slate-400">{formData.tagline}</p>
              <p className="text-[10px] text-slate-500 pt-1">
                Client: {formData.clientName} | {formData.contactEmail}
              </p>
            </div>
          </div>

          {/* Footer Controls */}
          <div className="flex items-center justify-between pt-4 border-t border-slate-800">
            <button
              type="button"
              onClick={handleReset}
              className="flex items-center space-x-1.5 rtl:space-x-reverse px-3 py-1.5 rounded-lg text-slate-400 hover:text-white text-xs font-semibold"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>{t.resetDefaults}</span>
            </button>

            <div className="flex items-center space-x-2 rtl:space-x-reverse">
              <button
                type="button"
                onClick={onClose}
                className="px-4 py-2 rounded-xl text-xs font-semibold text-slate-400 hover:text-white"
              >
                {lang === 'ar' ? 'إلغاء' : 'Cancel'}
              </button>
              <button
                type="submit"
                className="flex items-center space-x-2 rtl:space-x-reverse px-5 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-bold shadow-lg shadow-indigo-600/30 transition-all"
              >
                {savedSuccess ? (
                  <>
                    <Check className="w-4 h-4 text-emerald-300" />
                    <span>{t.savedExclamation}</span>
                  </>
                ) : (
                  <>
                    <Save className="w-4 h-4" />
                    <span>{t.saveWhiteLabel}</span>
                  </>
                )}
              </button>
            </div>
          </div>

        </form>

      </div>
    </div>
  );
};
